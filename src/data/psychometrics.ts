export const psychDimensions = D.map(({ id, label }) => ({ id, label }));

export const allPsychQuestions: PsychQuestion[] = D.flatMap((dimension) =>
  dimension.items.map((item, index) => {
    const tuple = Array.isArray(item) ? item : [item, false] as const;
    return {
      id: `${dimension.id}_${String(index + 1).padStart(2, '0')}`,
      dimension: dimension.id,
      text: tuple[0],
      reverse: tuple[1] === true,
    };
  }),
);

// 各次元の最初の4問、合計60問。詳細版150問と同一スキーマ・同一質問IDを使う。
export const quickPsychQuestions = D.flatMap((dimension) =>
  allPsychQuestions.filter((q) => q.dimension === dimension.id).slice(0, 4),
);

export function scorePsychometrics(responses: Record<string, number | null>) {
  const scores: Record<string, number> = {};
  for (const dimension of psychDimensions) {
    const questions = allPsychQuestions.filter((q) => q.dimension === dimension.id);
    const values = questions
      .filter((q) => typeof responses[q.id] === 'number')
      .map((q) => {
        const raw = responses[q.id] as number;
        return q.reverse ? 6 - raw : raw;
      });
    if (values.length) scores[dimension.id] = Number((values.reduce((a, b) => a + b, 0) / values.length).toFixed(2));
  }

  const pairedDiffs: number[] = [];
  for (const dimension of psychDimensions) {
    const qs = allPsychQuestions.filter((q) => q.dimension === dimension.id);
    for (let i = 0; i + 1 < qs.length; i += 2) {
      const a = responses[qs[i].id];
      const b = responses[qs[i + 1].id];
      if (typeof a === 'number' && typeof b === 'number') {
        const aAdjusted = qs[i].reverse ? 6 - a : a;
        const bAdjusted = qs[i + 1].reverse ? 6 - b : b;
        pairedDiffs.push(Math.abs(aAdjusted - bAdjusted));
      }
    }
  }
  if (pairedDiffs.length < 8) return { scores, consistency: 'insufficient' as const };
  const meanDiff = pairedDiffs.reduce((a, b) => a + b, 0) / pairedDiffs.length;
  const consistency = meanDiff <= 0.9 ? 'high' : meanDiff <= 1.6 ? 'medium' : 'low';
  return { scores, consistency } as const;
}
